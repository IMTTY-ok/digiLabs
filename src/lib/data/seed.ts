export function createSeedDatabase(): DemoDatabase {
  return {
    version: 1,
    seededAt: iso(0),
    institutions: [
      {
        id: INSTITUTION_ID,
        name: "Northline Institute of Engineering",
        shortName: "Northline",
        code: "NIE-014",
        city: "Pune, Maharashtra",
        academicYear: "2026–27",
      },
    ],
    users: USERS,
    students: STUDENTS,
    experiments: EXPERIMENTS,
    labAccess: LAB_ACCESS,
    assignments: Object.entries(LAB_ACCESS).flatMap(([studentId, labs]) =>
      labs.flatMap((labId) =>
        EXPERIMENTS.filter((experiment) => experiment.labId === labId).map((experiment) => ({
          id: `as_${studentId}_${experiment.id}`,
          studentId,
          experimentId: experiment.id,
          assignedBy: "u_instructor",
          assignedAt: iso(20),
        })),
      ),
    ),
    equipment: EQUIPMENT,
    equipmentEvents: EQUIPMENT_EVENTS,
    safetyEvents: SAFETY_EVENTS,
    progress: PROGRESS,
    quizResults: QUIZ_RESULTS,
    sessions: SESSIONS,
    observations: OBSERVATIONS,
  };
}
